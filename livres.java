public class livres {
    public int idLivre;
    public String nomLivre;
    public livres(int idLivre, String nomLivre) {
        this.idLivre = idLivre;
        this.nomLivre = nomLivre;
    }
    public String getNomLivre() { return nomLivre; }
    public int getIdLivre() { return idLivre; }
}
